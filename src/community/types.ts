// Community data contract. Owned by the orchestrator: the issue form / aggregation task and the UI task
// both build against this file. Framework-free.
import type { MicProfile, NoiseKind, NoiseTone, StepKey, VoiceStyle } from '../types'
import type { SuggestionJson } from '../settings/suggest'

export const COMMUNITY_REPO = 'dev-vinicius-andrade/voice-check-bench'
export const COMMUNITY_LABEL = 'mic-result'
/** Issue form file in .github/ISSUE_TEMPLATE/. */
export const COMMUNITY_TEMPLATE = 'mic-result.yml'
/** Issue form field id that receives the summary JSON (pre-filled through the `summary` URL parameter). */
export const COMMUNITY_SUMMARY_FIELD = 'summary'
/** Served by the app (public/community/mics.json), regenerated by the GitHub Action. */
export const COMMUNITY_INDEX_PATH = 'community/mics.json'

/** What a person shares (the "anonymized summary"). No audio, no device names, no dates, no ids. */
export interface CommunitySummary {
  app: 'voice-check-bench'
  version: 1
  mic: MicProfile
  takes: {
    step: StepKey | null
    analysis: {
      speechMed: number
      noise: number
      snr: number
      rel: number[]
      /** Entries are null (NaN in memory) when the take had no usable silence window. */
      bandSnr: (number | null)[]
      tones: NoiseTone[]
      /** null for takes recorded before noise diagnosis existed. */
      noiseKind: NoiseKind | null
      spread: number
      sibP95: number
    }
  }[]
  suggestion: Omit<SuggestionJson, 'basedOn'> | null
  /** The voice goal's style (v0.9), so stats can be split by style; perceived issues are never shared. Absent in older reports. */
  goalStyle?: VoiceStyle
}

export interface Spread {
  median: number
  p25: number
  p75: number
}

export interface CommunityMicStats {
  /** micKey(model). */
  key: string
  /** Most common spelling among reports. */
  model: string
  reports: number
  kind: MicProfile['kind']
  pattern: MicProfile['pattern']
  address: MicProfile['address']
  /** SNR of raw control takes (c2/c8/c15). */
  rawSnr: Spread
  /** Noise floor of raw control takes, dBFS. */
  noise: Spread
  /** Median tone deviation vs the reference voice per BANDS entry, from each report's best raw control take. */
  deviations: number[]
  /** Votes for the best control distance ('2 cm' | '8 cm' | '15 cm'), most votes first. */
  bestDistance: { dist: string; votes: number }[]
  /** Processed SNR minus raw SNR at the same session, when the report has a processed take. */
  processedSnrGain: Spread | null
  /** Median suggested EQ per (type, freq) over reports, excluding notches; most reported first. */
  eq: { type: 'Low Shelf' | 'Band' | 'High Shelf'; freq: number; gainMedian: number; reports: number }[]
  /** Share of reports whose suggestion was noisyRoom (0..1). */
  noisyRoomShare: number
  /** One entry per counted report that has a suggestion, most votes first (v1.2). Absent in older index files. */
  solutions?: CommunitySolution[]
}

/** Settings one person shared, ranked by the 👍 reactions on its issue (v1.2). */
export interface CommunitySolution {
  /** Issue number (link: https://github.com/${COMMUNITY_REPO}/issues/<issue>). Also the "newest" order. */
  issue: number
  /** 👍 reactions on the issue. */
  votes: number
  /** goalStyle of the report, null when absent. */
  style: VoiceStyle | null
  /** The report's suggestion was made for a noisy room. */
  noisyRoom: boolean
  /** SNR of the report's best raw control take, dB (rounded 0.1). */
  rawSnr: number
  /** Distance of that best raw control take ('2 cm' | '8 cm' | '15 cm'). */
  dist: string
  /** Processed SNR minus best raw SNR, when the report has a processed (fx) take; else null. */
  snrGain: number | null
  suggestion: Omit<SuggestionJson, 'basedOn'>
}

export interface CommunityIndex {
  version: 1
  generated: string
  source: string
  /** Total valid reports used. */
  reports: number
  mics: CommunityMicStats[]
}

/** Labels the issue checker sets (tools/community/review.ts). `rejected` is only set by hand and always wins. */
export const COMMUNITY_REVIEW_LABELS = {
  accepted: 'accepted',
  invalid: 'invalid',
  duplicate: 'duplicate',
  rejected: 'rejected',
} as const

/** Manual mic-name corrections, tools/community/aliases.json. Keys are micKey() values. */
export interface MicAliases {
  /** micKey → canonical micKey ("k688" → "fifinek688"). */
  aliases: Record<string, string>
  /** Pairs of micKeys that look alike but are different mics; fuzzy matching never joins them. */
  distinct: [string, string][]
}

/** A mic-result issue as the checker and the aggregator see it (bodies are untrusted). */
export interface CommunityIssue {
  number: number
  /** GitHub login of the author. Never written to mics.json. */
  author: string
  body: string
  labels: string[]
  state: 'open' | 'closed'
  /** 👍 reactions. */
  votes: number
}

/** How a report's model name was matched to a known mic. */
export interface MicMatch {
  /** Canonical micKey the report counts under. */
  key: string
  /** Display name of that mic (most common spelling among its reports, or the report's own for a new mic). */
  model: string
  how: 'new' | 'exact' | 'alias' | 'fuzzy'
}

/** Checker verdict for one issue. */
export type ReviewVerdict =
  | { kind: 'accepted'; mic: MicMatch; /** Earlier issue by the same author for the same mic, now replaced in the stats. */ replaces: number | null }
  | { kind: 'invalid'; /** English, for the issue comment: what is wrong ("mic.model", "Summary block missing"). */ problem: string }
  | { kind: 'duplicate'; /** Issue with the identical Summary that counts instead. */ of: number }
  | { kind: 'rejected' }

/** Normalized model key: "Fifine K688", "fifine-k688 " → "fifinek688". Empty model → ''. */
export const micKey = (model: string): string =>
  model
    .normalize('NFKD')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '')
