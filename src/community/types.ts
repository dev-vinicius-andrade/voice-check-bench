// Community data contract. Owned by the orchestrator: the issue form / aggregation task and the UI task
// both build against this file. Framework-free.
import type { MicProfile, NoiseKind, NoiseTone, StepKey } from '../types'
import type { SuggestionJson } from '../settings/suggest'

export const COMMUNITY_REPO = 'dev-vinicius-andrade/voice-check-bench'
export const COMMUNITY_LABEL = 'mic-result'
/** Issue form file in .github/ISSUE_TEMPLATE/. */
export const COMMUNITY_TEMPLATE = 'mic-result.yml'
/** Issue form field id that receives the summary JSON (pre-filled through the `summary` URL parameter). */
export const COMMUNITY_SUMMARY_FIELD = 'summary'
/** Served by the app (public/community/mics.json), regenerated by the GitHub Action. */
export const COMMUNITY_INDEX_PATH = 'community/mics.json'

/** What a person shares (the "anonymized summary"). No audio, no device names, no dates, no ids. */
export interface CommunitySummary {
  app: 'voice-check-bench'
  version: 1
  mic: MicProfile
  takes: {
    step: StepKey | null
    analysis: {
      speechMed: number
      noise: number
      snr: number
      rel: number[]
      bandSnr: number[]
      tones: NoiseTone[]
      noiseKind: NoiseKind
      spread: number
      sibP95: number
    }
  }[]
  suggestion: Omit<SuggestionJson, 'basedOn'> | null
}

export interface Spread {
  median: number
  p25: number
  p75: number
}

export interface CommunityMicStats {
  /** micKey(model). */
  key: string
  /** Most common spelling among reports. */
  model: string
  reports: number
  kind: MicProfile['kind']
  pattern: MicProfile['pattern']
  address: MicProfile['address']
  /** SNR of raw control takes (c2/c8/c15). */
  rawSnr: Spread
  /** Noise floor of raw control takes, dBFS. */
  noise: Spread
  /** Median tone deviation vs the reference voice per BANDS entry, from each report's best raw control take. */
  deviations: number[]
  /** Votes for the best control distance ('2 cm' | '8 cm' | '15 cm'), most votes first. */
  bestDistance: { dist: string; votes: number }[]
  /** Processed SNR minus raw SNR at the same session, when the report has a processed take. */
  processedSnrGain: Spread | null
  /** Median suggested EQ per (type, freq) over reports, excluding notches; most reported first. */
  eq: { type: 'Low Shelf' | 'Band' | 'High Shelf'; freq: number; gainMedian: number; reports: number }[]
  /** Share of reports whose suggestion was noisyRoom (0..1). */
  noisyRoomShare: number
}

export interface CommunityIndex {
  version: 1
  generated: string
  source: string
  /** Total valid reports used. */
  reports: number
  mics: CommunityMicStats[]
}

/** Normalized model key: "Fifine K688", "fifine-k688 " → "fifinek688". Empty model → ''. */
export const micKey = (model: string): string =>
  model
    .normalize('NFKD')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '')
